"""Generates the third factory preset set (engine/src/PresetLibrary3*.inc) from the spec_*.py files.

Each spec module defines PRESETS, a list of preset(...) entries in table order. Patch levels come from
levels.json (written by level.py from kmi_render measurements); a preset without one starts at 1.0.

    python scripts/presets3/gen.py
"""
import importlib.util
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
SPECS = ['spec_keys', 'spec_bass_lead', 'spec_pads', 'spec_misc']


def load_presets():
    out = []
    for name in SPECS:
        path = os.path.join(HERE, name + '.py')
        if not os.path.exists(path):
            continue
        spec = importlib.util.spec_from_file_location(name, path)
        mod = importlib.util.module_from_spec(spec)
        sys.path.insert(0, HERE)
        spec.loader.exec_module(mod)
        out.extend(mod.PRESETS)
    return out


def fn_name(name):
    words = re.findall(r'[A-Za-z0-9]+', name)
    s = ''.join(w[:1].upper() + w[1:] for w in words)
    return 'p3' + s


def main():
    presets = load_presets()
    levels_path = os.path.join(HERE, 'levels.json')
    levels = json.load(open(levels_path)) if os.path.exists(levels_path) else {}
    boosts_path = os.path.join(HERE, 'boosts.json')
    boosts = json.load(open(boosts_path)) if os.path.exists(boosts_path) else {}
    names = [p['name'] for p in presets]
    assert len(set(names)) == len(names), 'duplicate preset names'
    older = set()
    for fname in ('Presets.cpp', 'PresetLibraryEntries.inc'):
        older |= set(re.findall(r'\{ \{ "([^"]+)", "', open(os.path.join(ROOT, 'engine', 'src', fname), encoding='utf-8').read()))
    clash = sorted(older & set(names))
    assert not clash, 'names already used by earlier presets: %s' % clash

    code = ['// Factory preset library, part 3. GENERATED by scripts/presets3/gen.py from the spec files: edit those,',
            '// not this file. Included by Presets.cpp inside its anonymous namespace.', '']
    entries = ['// Factory preset library, part 3: table entries. GENERATED by scripts/presets3/gen.py.']
    tags = ['// Factory preset library, part 3: search tags. GENERATED by scripts/presets3/gen.py.']
    last_cat = None
    for p in presets:
        if p['category'] != last_cat:
            bar = '// ' + '=' * 96
            code += [bar, '// ' + p['category'], bar, '']
            last_cat = p['category']
        body = '\n'.join('    ' + line.strip() if line.strip() else '' for line in p['body'].strip('\n').split('\n'))
        level = levels.get(p['name'], 1.0)
        boost = boosts.get(p['name'], 1.0)
        boost_line = ['    boostCarriers(p, %.2ff);' % boost] if boost > 1.0 else []
        code += ['// ' + p['desc'], 'Patch %s()' % fn_name(p['name']), '{', body] + boost_line + [
                 '    p.vca.patchLevel = %.2ff; // level-matched across the bank' % level, '    return p;', '}', '']
        style = ', "%s"' % p['style'] if p.get('style') else ''
        entries.append('    { { "%s", "%s", "%s", %d, %s%s }, %s },' % (
            p['name'], p['category'], p['desc'], p['note'], 'true' if p['sustained'] else 'false', style, fn_name(p['name'])))
        tags.append('        %-45s // %s' % ('"%s",' % p['tags'], p['name']))

    src = os.path.join(ROOT, 'engine', 'src')
    for fname, lines in (('PresetLibrary3.inc', code), ('PresetLibrary3Entries.inc', entries), ('PresetLibrary3Tags.inc', tags)):
        with open(os.path.join(src, fname), 'w', encoding='utf-8', newline='\n') as f:
            f.write('\n'.join(lines) + '\n')
    print('%d presets generated' % len(presets))


if __name__ == '__main__':
    main()
